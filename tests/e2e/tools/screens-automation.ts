import '../output.ts'; // screenshots go outside the repository
import { chromium } from 'playwright';
const B = 'http://localhost:8080';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1254/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const api = async (method: string, path: string, body?: any, token?: string | null) => (await fetch(B + '/api' + path, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: body ? JSON.stringify(body) : undefined })).json();
const token = (await api('POST', '/auth/login', { email: 'admin@acme.test', password: 'supersecret1' })).access_token;
const s = Date.now().toString(36);
const cat = (await api('POST', '/crm/deal/categories', { name: `Shots ${s}` }, token)).categories.find((c) => c.name === `Shots ${s}`);
const st = Object.fromEntries(cat.stages.map((x) => [x.name, x.id]));
const R = (b) => api('POST', '/crm/robots', { category_id: cat.id, ...b }, token);
await R({ stage_id: st.New, name: 'Welcome call', action: 'activity', params: { kind: 'call', subject: 'Call {{title}}', deadline_minutes: 60 } });
await R({ stage_id: st.New, name: 'Remind before close', action: 'notify', params: { message: '{{title}} closes soon' }, timing: 'field', timing_field: 'close_date', offset_minutes: -2880 });
await R({ stage_id: st['Proposal sent'], name: 'Send proposal', action: 'email', params: { subject: 'Proposal {{title}}', body: 'Attached.' } , wait: { until: 'activity_done', timeout_minutes: 2880, on_timeout: 'run' } });
await R({ stage_id: st['Proposal sent'], name: 'Nudge', action: 'comment', params: { text: 'nudge' }, after_previous: true, delay_minutes: 1440 });
await R({ stage_id: st.Won, name: 'Sync to ERP', action: 'webhook', params: { url: 'https://erp.example.com/hooks/deals', method: 'POST' } });
await api('PATCH', `/crm/stages/${st.Preparation}`, { sla_minutes: 2880, sla_escalate: true }, token);
await page.goto(B + '/login'); await page.fill('#email', 'admin@acme.test'); await page.fill('#password', 'supersecret1');
await page.click('button:has-text("Sign in")'); await page.waitForURL(B + '/');
await page.goto(B + '/crm/settings?tab=automation');
await page.selectOption('select[aria-label="Pipeline"]', cat.id);
await page.locator('text=Sync to ERP').waitFor();
await page.screenshot({ path: '30-automation-rules.png' });
await page.click('text=Remind before close');
await page.locator('dialog[open]').waitFor(); await page.waitForTimeout(300);
await page.screenshot({ path: '31-robot-editor.png' });
await page.click('dialog button:has-text("Cancel")');
await page.click('text=Send proposal'); await page.locator('dialog[open]').waitFor();
await page.locator('dialog[open] >> text=Wait before acting').scrollIntoViewIfNeeded(); await page.waitForTimeout(300);
await page.screenshot({ path: '32-robot-wait.png' });
await page.click('dialog button:has-text("Cancel")');
await page.click('button[role=tab]:has-text("Log")'); await page.waitForTimeout(1200);
await page.screenshot({ path: '33-log.png' });
await page.click('button[role=tab]:has-text("Schedules")');
await page.click('button.btn-primary:has-text("Schedule")'); await page.locator('dialog[open]').waitFor(); await page.waitForTimeout(300);
await page.screenshot({ path: '34-schedule-editor.png' });
await page.goto(B + '/');
await api('DELETE', `/crm/categories/${cat.id}`, null, token);
await browser.close();
